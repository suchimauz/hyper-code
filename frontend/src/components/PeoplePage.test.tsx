import { render, screen, act, cleanup } from '@testing-library/react';
import { afterEach, expect, test, vi } from 'vitest';
import { PeoplePage } from './PeoplePage';
const mocks=vi.hoisted(()=>({request:vi.fn(),subscribe:vi.fn(),unsubscribe:vi.fn()}));
vi.mock('../sdk/api',()=>({requestJson:mocks.request}));
vi.mock('../sdk/live',()=>({subscribeLive:mocks.subscribe}));
afterEach(()=>{cleanup();vi.clearAllMocks();});
test('native presence updates, resyncs and disposes without displaying private stream data',async()=>{
  let onlineIds=['alice'];
  mocks.request.mockImplementation(async(path:string)=>path==='/auth/online'?{onlineIds}:{meId:'alice',csrfToken:'test',google:null,users:[{id:'alice',name:'Alice',email:null,role:'owner',disabledAt:null,hasPassword:true,providers:[]}]});
  mocks.subscribe.mockReturnValue(mocks.unsubscribe);
  const view=render(<PeoplePage/>);
  await screen.findByText('Online');
  expect(view.container.querySelector('[data-live-topic="presence"]')).not.toBeNull();
  const subscription=mocks.subscribe.mock.calls[0][0];
  expect(subscription.types).toEqual(['presence']);
  onlineIds=[];
  act(()=>subscription.onEvent({type:'presence'}));
  await screen.findByText('Offline');
  onlineIds=['alice'];
  act(()=>subscription.resync('reconnect'));
  await screen.findByText('Online');
  act(()=>subscription.onError(new Error('offline')));
  await screen.findByText('Presence unavailable');
  const last=mocks.request.mock.calls.filter(([path])=>path==='/auth/online').at(-1)!;
  view.unmount();
  expect(mocks.unsubscribe).toHaveBeenCalledTimes(1);
  expect(last[1].signal.aborted).toBe(true);
});
